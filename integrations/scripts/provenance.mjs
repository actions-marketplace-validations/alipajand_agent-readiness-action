// Records which engine commits the integrations bundle. The values come from the
// checked-out submodules, and the build refuses to run when a submodule is not
// at the commit the repository records, so the bundle and the pins cannot drift.
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');

const ENGINES = [
  { key: 'readiness', dir: 'vendor/agent-readiness-kit' },
  { key: 'context', dir: 'vendor/agent-context-doctor' },
];

function git(args, cwd = root) {
  return execFileSync('git', args, { cwd, encoding: 'utf8' }).trim();
}

export function readProvenance() {
  const engines = {};
  for (const { key, dir } of ENGINES) {
    const checkedOut = git(['rev-parse', 'HEAD'], path.join(root, dir));
    // `git ls-files -s` prints "160000 <sha> 0\t<path>" for a gitlink.
    const recorded = git(['ls-files', '-s', '--', dir]).split(/\s+/)[1];
    if (checkedOut !== recorded) {
      throw new Error(
        `${dir} is checked out at ${checkedOut} but the repository records ${recorded}. ` +
          'Run `git submodule update --init` or stage the submodule bump first.',
      );
    }
    const pkg = JSON.parse(readFileSync(path.join(root, dir, 'package.json'), 'utf8'));
    const repository = String(pkg.repository?.url ?? '')
      .replace(/^git\+/, '')
      .replace(/\.git$/, '');
    engines[key] = { name: pkg.name, version: pkg.version, commit: checkedOut, repository };
  }
  return engines;
}

export function writeProvenanceModule(target) {
  const engines = readProvenance();
  const body =
    '// Generated by integrations/scripts/provenance.mjs. Do not edit.\n' +
    `export const ENGINE_PROVENANCE = ${JSON.stringify(engines, null, 2)} as const;\n`;
  writeFileSync(target, body);
  return engines;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  console.log(JSON.stringify(readProvenance(), null, 2));
}
